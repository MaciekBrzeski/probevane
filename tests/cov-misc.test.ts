const CMDS: AdapterCommands = { typecheck: 'tc', lint: 'l', testUnit: 'tu', testE2e: 'te', coverage: 'cov' };

function fakeAdapter(over: Partial<StackAdapter> = {}): StackAdapter {
  return {
    id: 'fake-stack',
    coverage: async () => ({ statements: 88, branches: 70, functions: 90, lines: 88, ok: true }),
    probe: async (_dir: string, target): Promise<ProbeResult> => ({
      target,
      facts: {},
      digest: `Module ${target.sourcePath}\n- exports: foo, bar\n- note: stuff`,
      ok: true,
    }),
    commands: () => CMDS,
    ...over,
  } as unknown as StackAdapter;
}

/** A tiny project with three modules that import each other + one fetcher. */
function makeProject(): string {
  const dir = mkTmp();
  const src = join(dir, 'src');
  mkdirSync(src, { recursive: true });
  writeFileSync(join(src, 'util.ts'), `export const TAX = 0.2;\nexport function calc(n: number) { return n * TAX; }\n`);
  writeFileSync(
    join(src, 'api.ts'),
    `import { calc } from './util.js';\nconst BASE = '/api';\nexport async function getProducts() { const r = await fetch(\`\${BASE}/products\`); return r.json(); }\nexport function priced(n: number) { return calc(n); }\n`,
  );
  writeFileSync(
    join(src, 'widget.tsx'),
    `import { getProducts } from './api.js';\nexport default function Widget() { void getProducts; return null; }\n`,
  );
  return dir;
}

describe('spec/build buildSpec', () => {
  it('assembles the full markdown spec (overview/graph/modules/api) without a brain', async () => {
    const dir = makeProject();
    const opts: SpecOptions = { dir, adapter: fakeAdapter(), stamp: '2026-01-01' };
    const md = await buildSpec(opts);

    // header + stamp
    expect(md).toContain('— Specification');
    expect(md).toContain('Generated by probevane (fake-stack) on 2026-01-01');
    // overviewLines: graph summary + endpoint count + coverage
    expect(md).toContain('## Overview');
    expect(md).toContain('3 modules');
    expect(md).toContain('network endpoint(s)');
    expect(md).toContain('test coverage: 88% statements, 70% branches');
    // graphLines: ascii + mermaid
    expect(md).toContain('## Module graph');
    expect(md).toContain('```mermaid');
    // modulesLines + moduleSection: per-module header, net emoji, probe facts
    expect(md).toContain('## Modules');
    expect(md).toContain('### src/api.ts');
    expect(md).toContain('🌐'); // api is a fetcher (callsNetwork)
    expect(md).toContain('- exports: foo, bar'); // probe digest facts injected
    expect(md).toContain('depends on:'); // api/widget have local deps
    // apiLines (non-empty): API surface from the synthesized handler
    expect(md).toContain('## API surface');
    expect(md).toContain('GET /api/products');
  });

  it('covers the empty/catch branches: coverage() rejects, probe ok:false, no stamp', async () => {
    const dir = makeProject();
    const adapter = fakeAdapter({
      coverage: async () => {
        throw new Error('no coverage');
      },
      probe: async (_dir: string, target): Promise<ProbeResult> => ({
        target,
        facts: {},
        digest: '',
        ok: false,
        error: 'probe failed',
      }),
    });
    const md = await buildSpec({ dir, adapter });

    expect(md).toContain('## Overview');
    expect(md).not.toContain('test coverage:'); // cov null → no coverage line
    expect(md).not.toContain(' on '); // no stamp → no " on <stamp>"
    expect(md).toContain('## Modules'); // still renders module sections
    expect(md).not.toContain('- exports:'); // probe ok:false → no facts injected
  });
});

