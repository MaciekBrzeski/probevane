const FINDING: Finding = { file: 'src/a.ts', line: 3, severity: 'error', issue: 'off-by-one', fix: 'use <=' };

function fakeBrain(text: string, throws = false): Brain {
  return {
    id: 'fake',
    model: 'fake',
    async complete() {
      if (throws) throw new Error('brain down');
      return { text, toolCalls: [], stopReason: 'end_turn', usage: { input: 0, output: 0 } };
    },
  };
}

describe('review/diff-review', () => {
  it('parseFindings: valid JSON array → normalized findings', () => {
    const out = parseFindings(JSON.stringify([FINDING]));
    expect(out).toEqual([FINDING]);
  });

  it('parseFindings: fenced ```json block is extracted', () => {
    const out = parseFindings('here you go:\n```json\n' + JSON.stringify([FINDING]) + '\n```\nthanks');
    expect(out).toHaveLength(1);
    expect(out[0].file).toBe('src/a.ts');
  });

  it('parseFindings: garbage → [] and non-array → []', () => {
    expect(parseFindings('no json at all')).toEqual([]);
    expect(parseFindings('{"not":"an array"}')).toEqual([]);
  });

  it('parseFindings: normalizes severity, line, fix and drops incomplete entries', () => {
    const raw = JSON.stringify([
      { file: 'x.ts', issue: 'bad sev', severity: 'critical', line: 'NaN' }, // sev→warn, line→undefined, fix→''
      { file: 'y.ts', issue: 'no fix', severity: 'nit', line: 7 },
      { severity: 'error', issue: 'no file' }, // dropped (no file)
      { file: 'z.ts', severity: 'error' }, // dropped (no issue)
    ]);
    const out = parseFindings(raw);
    expect(out).toEqual([
      { file: 'x.ts', line: undefined, severity: 'warn', issue: 'bad sev', fix: '' },
      { file: 'y.ts', line: 7, severity: 'nit', issue: 'no fix', fix: '' },
    ]);
  });

  it('findingsMarkdown: empty → clean message; non-empty → icons + locations + fixes', () => {
    expect(findingsMarkdown([])).toContain('No issues found');
    const md = findingsMarkdown([
      FINDING,
      { file: 'b.ts', severity: 'nit', issue: 'style', fix: '' },
    ]);
    expect(md).toContain('2 finding(s)');
    expect(md).toContain('🛑');
    expect(md).toContain('`src/a.ts:3`');
    expect(md).toContain('→ use <=');
    expect(md).toContain('💡');
    expect(md).toContain('`b.ts`'); // no line → no :line suffix
  });

  it('findingsTask renders a numbered remediation task', () => {
    const task = findingsTask([FINDING, { file: 'b.ts', severity: 'warn', issue: 'leak', fix: 'close it' }]);
    expect(task).toContain('A code review found');
    expect(task).toContain('1. [error] src/a.ts:3 — off-by-one (suggested: use <=)');
    expect(task).toContain('2. [warn] b.ts — leak (suggested: close it)');
  });

  it('getDiff returns sliced sh stdout; empty stdout → empty string', async () => {
    shMock.mockResolvedValue({ code: 0, stdout: 'diff --git a b\n+added', stderr: '', ok: true });
    expect(await getDiff(mkTmp(), 'HEAD')).toContain('+added');
    shMock.mockResolvedValue({ code: 0, stdout: '', stderr: '', ok: true });
    expect(await getDiff(mkTmp(), 'HEAD')).toBe('');
  });

  it('reviewDiffText: empty diff short-circuits to []', async () => {
    expect(await reviewDiffText('   ', fakeBrain('[]'))).toEqual([]);
  });

  it('reviewDiffText: parses a fake brain reply', async () => {
    const out = await reviewDiffText('some real diff', fakeBrain(JSON.stringify([FINDING])));
    expect(out).toEqual([FINDING]);
  });

  it('reviewDiffText: brain failure → catch → []', async () => {
    expect(await reviewDiffText('some real diff', fakeBrain('', true))).toEqual([]);
  });

  it('reviewDiff: wires getDiff(sh) → reviewDiffText(brain)', async () => {
    shMock.mockResolvedValue({ code: 0, stdout: 'a real diff body', stderr: '', ok: true });
    const out = await reviewDiff(mkTmp(), 'HEAD', fakeBrain(JSON.stringify([FINDING])));
    expect(out).toEqual([FINDING]);
  });
});
