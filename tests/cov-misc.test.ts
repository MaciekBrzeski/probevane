describe('brain/select brainFor', () => {
  const saved = process.env.PROBEVANE_RECORD;
  beforeEach(() => {
    delete process.env.PROBEVANE_RECORD;
  });
  afterEach(() => {
    if (saved === undefined) delete process.env.PROBEVANE_RECORD;
    else process.env.PROBEVANE_RECORD = saved;
  });

  it('undefined / auto → anthropic brain', () => {
    expect(brainFor().id).toBe('anthropic-sdk');
    expect(brainFor('auto').id).toBe('anthropic-sdk');
  });

  it('haiku/sonnet/opus resolve their aliased model ids', () => {
    expect(brainFor('haiku')).toMatchObject({ id: 'anthropic-sdk', model: 'claude-haiku-4-5-20251001' });
    expect(brainFor('sonnet').model).toBe('claude-sonnet-4-6');
    expect(brainFor('opus').model).toBe('claude-opus-4-8');
  });

  it('an unknown model id passes through as-is (alias fallback)', () => {
    expect(brainFor('claude-custom-9')).toMatchObject({ id: 'anthropic-sdk', model: 'claude-custom-9' });
  });

  it('bridge / claude-code / cc:<m> branches', () => {
    expect(brainFor('bridge')).toMatchObject({ id: 'bridge', model: 'bridge' });
    expect(brainFor('claude-code')).toMatchObject({ id: 'claude-code', model: 'claude-code' });
    expect(brainFor('cc:gpt')).toMatchObject({ id: 'claude-code', model: 'claude-code:gpt' });
  });

  it('local:<id> / openai:<id> → openai-compat brain', () => {
    expect(brainFor('local:qwen')).toMatchObject({ id: 'openai-compat', model: 'qwen' });
    expect(brainFor('openai:gpt-4o')).toMatchObject({ id: 'openai-compat', model: 'gpt-4o' });
  });

  it('replay:<file> → replay brain (and bypasses PROBEVANE_RECORD wrapping)', () => {
    expect(brainFor('replay:/tmp/cassette.jsonl').id).toBe('replay');
    process.env.PROBEVANE_RECORD = join(mkTmp(), 'rec.jsonl');
    expect(brainFor('replay:/tmp/cassette.jsonl').id).toBe('replay'); // returns before rec check
  });

  it('PROBEVANE_RECORD wraps a live brain in a recording brain', () => {
    process.env.PROBEVANE_RECORD = join(mkTmp(), 'rec.jsonl');
    expect(brainFor('local:qwen').id).toBe('record(openai-compat)');
    expect(brainFor('opus').id).toBe('record(anthropic-sdk)');
  });
});

