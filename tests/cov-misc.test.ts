function gitCmd(dir: string, ...args: string[]): string {
  return execFileSync('git', args, { cwd: dir, stdio: ['ignore', 'pipe', 'ignore'] }).toString();
}
function makeRepo(): string {
  const dir = mkTmp();
  gitCmd(dir, 'init', '-b', 'main');
  gitCmd(dir, 'config', 'user.email', 'tester@example.com');
  gitCmd(dir, 'config', 'user.name', 'Tester');
  writeFileSync(join(dir, 'a.txt'), 'hello\n');
  gitCmd(dir, 'add', 'a.txt');
  gitCmd(dir, 'commit', '-m', 'init');
  return dir;
}

describe('util/git in a real temp repo', () => {
  it('isGitRepo / repoRoot / headSha / currentBranch (repo + non-repo)', async () => {
    const repo = makeRepo();
    const bare = mkTmp();

    expect(await git.isGitRepo(repo)).toBe(true);
    expect(await git.isGitRepo(bare)).toBe(false);

    expect(await git.repoRoot(repo)).toBe(realpathSync(repo));
    expect(await git.repoRoot(bare)).toBe('');

    expect(await git.headSha(repo)).toMatch(/^[0-9a-f]{40}$/);
    expect(await git.headSha(bare)).toBe('');

    expect(await git.currentBranch(repo)).toBe('main');
    expect(await git.currentBranch(bare)).toBe('');
  });

  it('diffStat reflects working-tree edits; clean tree is empty', async () => {
    const repo = makeRepo();
    expect(await git.diffStat(repo)).toBe('');
    expect(await git.diffStat(repo, 'HEAD')).toBe(''); // base-arg branch
    writeFileSync(join(repo, 'a.txt'), 'hello\nworld\n');
    expect(await git.diffStat(repo)).toContain('a.txt');
  });

  it('fileExistedAt / showFile resolve content at a sha; absent → false / empty', async () => {
    const repo = makeRepo();
    const sha = await git.headSha(repo);
    expect(await git.fileExistedAt(repo, sha, 'a.txt')).toBe(true);
    expect(await git.fileExistedAt(repo, sha, 'ghost.txt')).toBe(false);
    expect(await git.showFile(repo, sha, 'a.txt')).toBe('hello\n');
    expect(await git.showFile(repo, sha, 'ghost.txt')).toBe('');
    expect(await git.showFile(repo, '', 'a.txt')).toBe(''); // empty sha → early ''
    expect(await git.headSha(bareDir())).toBe('');
  });
  function bareDir() {
    return mkTmp();
  }

  it('restoreFile rolls a file back to its committed content', async () => {
    const repo = makeRepo();
    const sha = await git.headSha(repo);
    writeFileSync(join(repo, 'a.txt'), 'corrupted\n');
    expect(await git.restoreFile(repo, sha, 'a.txt')).toBe(true);
    expect(readFileSync(join(repo, 'a.txt'), 'utf8')).toBe('hello\n');
  });

  it('createBranch switches branch; commitFiles needs files and commits them', async () => {
    const repo = makeRepo();
    expect(await git.commitFiles(repo, [], 'noop')).toBe(false); // empty file list
    writeFileSync(join(repo, 'b.txt'), 'second\n');
    expect(await git.commitFiles(repo, ['b.txt'], 'add b')).toBe(true);

    expect(await git.createBranch(repo, 'feature')).toBe(true);
    expect(await git.currentBranch(repo)).toBe('feature');
  });

  it('hasRemote is false without an origin', async () => {
    expect(await git.hasRemote(makeRepo())).toBe(false);
  });

  it('addWorktree + removeWorktree are safe in a temp repo', async () => {
    const repo = makeRepo();
    const wt = join(mkTmp(), 'wt');
    expect(await git.addWorktree(repo, wt, 'wt-branch')).toBe(true);
    expect(existsSync(wt)).toBe(true);
    await git.removeWorktree(repo, wt, 'wt-branch');
    expect(existsSync(wt)).toBe(false);
  });

  it('mergeBranch performs a no-ff merge of a feature commit', async () => {
    const repo = makeRepo();
    await git.createBranch(repo, 'feat');
    writeFileSync(join(repo, 'feat.txt'), 'feature\n');
    await git.commitFiles(repo, ['feat.txt'], 'feat commit');
    gitCmd(repo, 'checkout', 'main');
    expect(await git.mergeBranch(repo, 'feat', 'merge feat')).toBe(true);
    expect(existsSync(join(repo, 'feat.txt'))).toBe(true);
  });

  it('revertEdits restores tracked files and removes run-created ones', async () => {
    const repo = makeRepo();
    const sha = await git.headSha(repo);
    writeFileSync(join(repo, 'a.txt'), 'edited\n'); // existed at sha → restored
    writeFileSync(join(repo, 'new.txt'), 'created\n'); // not at sha → removed
    const res = await git.revertEdits(repo, sha, ['a.txt', 'new.txt']);
    expect(res).toEqual({ restored: 1, removed: 1 });
    expect(readFileSync(join(repo, 'a.txt'), 'utf8')).toBe('hello\n');
    expect(existsSync(join(repo, 'new.txt'))).toBe(false);
  });
});

