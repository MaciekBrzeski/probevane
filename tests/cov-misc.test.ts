describe('adapters/vitest-runner', () => {
  it('runVitest parses a green json report', async () => {
    const dir = mkTmp();
    writeFileSync(
      join(dir, '.probevane-vitest.json'),
      JSON.stringify({ numPassedTests: 5, numFailedTests: 0, numPendingTests: 1, numTodoTests: 0 }),
    );
    shMock.mockResolvedValue({ code: 0, stdout: 'out', stderr: '', ok: true });
    const r = await runVitest(dir);
    expect(r).toMatchObject({ passed: 5, failed: 0, skipped: 1, green: true });
  });

  it('runVitest: passing tests but failures present → not green', async () => {
    const dir = mkTmp();
    writeFileSync(join(dir, '.probevane-vitest.json'), JSON.stringify({ numPassedTests: 3, numFailedTests: 2 }));
    shMock.mockResolvedValue({ code: 1, stdout: '', stderr: 'boom', ok: false });
    const r = await runVitest(dir);
    expect(r).toMatchObject({ passed: 3, failed: 2, green: false });
  });

  it('runVitest: missing/unparsable report → catch branch, failed forced to >=1 when run failed', async () => {
    const dir = mkTmp(); // no report file written
    shMock.mockResolvedValue({ code: 1, stdout: '', stderr: 'crash', ok: false });
    const r = await runVitest(dir);
    expect(r.passed).toBe(0);
    expect(r.failed).toBeGreaterThanOrEqual(1);
    expect(r.green).toBe(false);
  });

  it('runVitest passes scoped files through to sh', async () => {
    const dir = mkTmp();
    writeFileSync(join(dir, '.probevane-vitest.json'), JSON.stringify({ numPassedTests: 1, numFailedTests: 0 }));
    shMock.mockResolvedValue({ code: 0, stdout: '', stderr: '', ok: true });
    await runVitest(dir, ['a.test.ts', 'b.test.ts']);
    const cmd = shMock.mock.calls[0][0] as string;
    expect(cmd).toContain('"a.test.ts"');
    expect(cmd).toContain('"b.test.ts"');
  });

  it('runPlaywright: green line-reporter output', async () => {
    shMock.mockResolvedValue({ code: 0, stdout: '3 passed (1.2s)', stderr: '', ok: true });
    const r = await runPlaywright(mkTmp());
    expect(r).toMatchObject({ passed: 3, failed: 0, green: true });
  });

  it('runPlaywright: failures + skips parsed, not green', async () => {
    shMock.mockResolvedValue({ code: 1, stdout: '1 passed\n2 failed\n1 skipped', stderr: '', ok: false });
    const r = await runPlaywright(mkTmp(), ['x.e2e.ts']);
    expect(r).toMatchObject({ passed: 1, failed: 2, skipped: 1, green: false });
  });

  it('runPlaywright: no tests at all → total 0, not green', async () => {
    shMock.mockResolvedValue({ code: 0, stdout: 'no tests found', stderr: '', ok: true });
    const r = await runPlaywright(mkTmp());
    expect(r).toMatchObject({ passed: 0, failed: 0, green: false });
  });

  it('mergeResults: single part returned unchanged', () => {
    const one = { passed: 2, failed: 0, skipped: 0, green: true, raw: 'x' };
    expect(mergeResults([one])).toBe(one);
  });

  it('mergeResults: aggregates counts and ANDs green', () => {
    const merged = mergeResults([
      { passed: 2, failed: 0, skipped: 1, green: true, raw: 'a' },
      { passed: 3, failed: 1, skipped: 0, green: false, raw: 'b' },
    ]);
    expect(merged).toMatchObject({ passed: 5, failed: 1, skipped: 1, green: false });
    expect(merged.raw).toContain('a');
    expect(merged.raw).toContain('b');
  });

  it('coverageVitest: parses coverage-summary.json when present', async () => {
    const dir = mkTmp();
    mkdirSync(join(dir, 'coverage'), { recursive: true });
    writeFileSync(
      join(dir, 'coverage', 'coverage-summary.json'),
      JSON.stringify({ total: { statements: { pct: 91 }, branches: { pct: 80 }, functions: { pct: 85 }, lines: { pct: 91 } } }),
    );
    shMock.mockResolvedValue({ code: 0, stdout: 'cov-stdout', stderr: '', ok: true });
    const c = await coverageVitest(dir);
    expect(c).toMatchObject({ statements: 91, branches: 80, functions: 85, lines: 91, ok: true });
    expect(c.raw).toContain('cov-stdout');
  });

  it('coverageVitest: missing summary → ok:false, raw from stdout+stderr', async () => {
    const dir = mkTmp(); // no coverage dir
    shMock.mockResolvedValue({ code: 1, stdout: 'so', stderr: 'se', ok: false });
    const c = await coverageVitest(dir);
    expect(c.ok).toBe(false);
    expect(c.statements).toBe(0);
    expect(c.raw).toContain('se');
  });
});

