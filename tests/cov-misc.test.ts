describe('config loadConfig / validateConfig / pick', () => {
  it('absent config → defaults to {}', async () => {
    expect(await loadConfig(mkTmp())).toEqual({});
  });

  it('valid probevane.config.json is parsed and merged', async () => {
    const dir = mkTmp();
    writeFileSync(join(dir, 'probevane.config.json'), JSON.stringify({ model: 'haiku', minTests: 3, mock: true }));
    expect(await loadConfig(dir)).toEqual({ model: 'haiku', minTests: 3, mock: true });
  });

  it('config with validation issues still loads but logs them', async () => {
    const dir = mkTmp();
    writeFileSync(join(dir, 'probevane.config.json'), JSON.stringify({ bogus: 1 }));
    const spy = vi.spyOn(console, 'error').mockImplementation(() => {});
    const cfg = await loadConfig(dir);
    expect(cfg).toEqual({ bogus: 1 });
    expect(spy).toHaveBeenCalled();
    spy.mockRestore();
  });

  it('invalid JSON → throws the load error (catch path)', async () => {
    const dir = mkTmp();
    writeFileSync(join(dir, 'probevane.config.json'), '{ this is not json ');
    await expect(loadConfig(dir)).rejects.toThrow(/failed to load probevane\.config\.json/);
  });

  it('validateConfig flags non-objects, unknown keys, wrong types, bad kind', () => {
    expect(validateConfig(null)).toEqual(['config must be an object']);
    expect(validateConfig('nope')).toEqual(['config must be an object']);
    expect(validateConfig({ maxStep: 1 })).toEqual(['unknown key "maxStep"']);
    expect(validateConfig({ minTests: '5' })).toEqual(['"minTests" must be number (got string)']);
    expect(validateConfig({ kind: 'wat' })).toEqual(['"kind" must be "unit" or "e2e"']);
    expect(validateConfig({ model: 'x', kind: 'unit', minTests: 2, mock: true })).toEqual([]);
  });

  it('validateConfig accepts the nested arch role block, rejects malformed ones', () => {
    expect(validateConfig({ arch: { glue: ['cli'], shared: ['util', 'cost'] } })).toEqual([]);
    expect(validateConfig({ arch: { glue: [] } })).toEqual([]);
    expect(validateConfig({ arch: 'cli' })).toEqual(['"arch" must be an object ({ glue?, shared? })']);
    expect(validateConfig({ arch: ['cli'] })).toEqual(['"arch" must be an object ({ glue?, shared? })']);
    expect(validateConfig({ arch: { blue: ['cli'] } })).toEqual(['unknown key "arch.blue"']);
    expect(validateConfig({ arch: { glue: 'cli' } })).toEqual(['"arch.glue" must be string[]']);
    expect(validateConfig({ arch: { shared: ['util', 7] } })).toEqual(['"arch.shared" must be string[]']);
  });

  it('pick returns the first defined value, else undefined', () => {
    expect(pick(undefined, 2, 3)).toBe(2);
    expect(pick('a')).toBe('a');
    expect(pick<number>(undefined, undefined)).toBeUndefined();
  });
});

